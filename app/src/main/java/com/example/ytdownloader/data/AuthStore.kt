package com.example.ytdownloader.data

import android.content.Context
import java.io.File

/**
 * Файл cookies в формате Netscape — единственное, что yt-dlp понимает как «вход в аккаунт».
 *
 * Раньше чтение, запись и удаление этого файла были размазаны по MainActivity,
 * а признак «пользователь авторизован» проверялся в трёх местах по-разному.
 */
class AuthStore(context: Context) {

    private val appContext = context.applicationContext
    private val cookiesFile = File(appContext.filesDir, COOKIES_FILE_NAME)

    fun isAuthorized(): Boolean = cookiesFile.exists() && cookiesFile.length() > MIN_FILE_LENGTH

    /** Путь для `--cookies`, если файл есть и непустой. */
    fun cookiesPath(): String? =
        cookiesFile.takeIf { it.exists() && it.length() > 0 }?.absolutePath

    /**
     * Переводит куки из WebView в Netscape-формат.
     * @return true, если в переданных строках нашлись признаки авторизации и файл записан.
     */
    fun saveFromCookieStrings(rawCookies: List<String>): Boolean {
        if (!hasAuthMarkers(rawCookies)) return false

        val builder = StringBuilder()
        builder.append("# Netscape HTTP Cookie File\n")
        builder.append("# Generated by YTDownloader\n\n")

        val addedNames = mutableSetOf<String>()
        for (raw in rawCookies) {
            for (item in raw.split(';')) {
                val part = item.trim()
                val eqIdx = part.indexOf('=')
                if (eqIdx <= 0) continue

                val name = part.substring(0, eqIdx).trim()
                val value = part.substring(eqIdx + 1).trim()
                if (name.isEmpty() || !addedNames.add(name)) continue

                appendCookie(builder, YOUTUBE_DOMAIN, name, value)
                appendCookie(builder, GOOGLE_DOMAIN, name, value)
            }
        }

        return try {
            cookiesFile.writeText(builder.toString())
            true
        } catch (e: Exception) {
            false
        }
    }

    fun clear() {
        runCatching { cookiesFile.delete() }
    }

    /** Признаки того, что пользователь действительно вошёл, а не просто открыл страницу. */
    fun hasAuthMarkers(rawCookies: List<String>): Boolean {
        val combined = rawCookies.joinToString("; ")
        return AUTH_MARKERS.any { combined.contains(it) }
    }

    private fun appendCookie(builder: StringBuilder, domain: String, name: String, value: String) {
        builder.append(domain)
            .append("\tTRUE\t/\tTRUE\t")
            .append(EXPIRY)
            .append('\t')
            .append(name)
            .append('\t')
            .append(value)
            .append('\n')
    }

    companion object {
        const val COOKIES_FILE_NAME = "youtube_cookies.txt"

        /** Домены, с которых CookieManager отдаёт куки после логина. */
        val COOKIE_DOMAINS = listOf(
            "https://www.youtube.com",
            "https://m.youtube.com",
            "https://youtube.com",
            "https://google.com",
            "https://accounts.google.com"
        )

        private val AUTH_MARKERS = listOf(
            "LOGIN_INFO",
            "SID",
            "SSID",
            "SAPISID",
            "__Secure-3PAPISID"
        )

        private const val YOUTUBE_DOMAIN = ".youtube.com"
        private const val GOOGLE_DOMAIN = ".google.com"
        private const val EXPIRY = "2147483647"

        /** Пустой файл или обрывок — не авторизация. */
        private const val MIN_FILE_LENGTH = 50L
    }
}
